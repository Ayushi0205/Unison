// `usedInCount` is the blast-radius signal — only ACTIVE templates count.
// Drafts haven't shipped (no live impact yet); Inactive templates aren't sending.
// Drafts are surfaced separately on the Partial Detail page as future blast radius;
// Inactive templates appear behind a toggle for historical audit only.
export function countActiveUses(partialId: string): number {
  return TEMPLATES.filter((t) => t.requiredPartialIds.includes(partialId) && t.lifecycle === 'Active').length
}

export const PARTIALS: Partial[] = loadCollection<Partial>('partials', RAW_PARTIALS).map((p) => ({
  ...p,
  usedInCount: countActiveUses(p.id),
}))

/** Save a created or edited partial (usedInCount is derived, so it's recomputed). */
export function savePartial(partial: Partial): void {
  upsert('partials', PARTIALS, { ...partial, usedInCount: countActiveUses(partial.id) }, 'start')
}
